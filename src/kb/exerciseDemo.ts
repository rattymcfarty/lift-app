/**
 * Exercise demo video resolution for the LIFT knowledge base.
 *
 * Demo clips are short, silent movement loops shown at the top of an exercise
 * guide. They live in `assets/exercises/demos/<kb-id>.mp4` and are bundled with
 * the app, so the guide works offline and in Expo Go with no network call.
 *
 * Metro cannot `require()` a dynamic path, so this module keeps a static
 * registry of the clips actually bundled. An exercise with no clip gets the
 * placeholder tile (the primary-muscle icon + "coming soon") — no guide ever
 * renders an empty media frame.
 *
 * The REGISTRY block is generated by `scripts/gen-exercise-demo-registry.mjs`.
 * Re-run that script after adding a clip. The file name must be the exercise's
 * permanent KB id (the same id the seeded exercise row uses).
 *
 * Clip contract (enforced by `scripts/test-exercise-demo.mjs`):
 *   720 × 720, 24 fps, 3 s loop, H.264 High, yuv420p, no audio, ≤ 500 KB.
 */

/** Every bundled clip must match this contract. */
export const DEMO_SPEC = {
  size: 720,
  fps: 24,
  seconds: 3,
  maxBytes: 500_000,
} as const;

// === BEGIN GENERATED REGISTRY ===
const REGISTRY: Record<string, number> = {
  'bench-press-powerlifting': require('../../assets/exercises/demos/bench-press-powerlifting.mp4'),
};
// === END GENERATED REGISTRY ===

/**
 * The bundled clip for an exercise, or null when it has none yet.
 * Pass the exercise's `kbId` (seeded rows use the KB id as their row id too).
 */
export function resolveExerciseDemo(exerciseId?: string | null): number | null {
  if (!exerciseId) return null;
  return REGISTRY[exerciseId] ?? null;
}

/** True when a real clip is bundled for this exercise. */
export function hasExerciseDemo(exerciseId?: string | null): boolean {
  return !!exerciseId && !!REGISTRY[exerciseId];
}

/** The KB ids that currently have a clip — used by the registry test. */
export function bundledDemoIds(): string[] {
  return Object.keys(REGISTRY).sort();
}
