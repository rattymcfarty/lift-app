/**
 * Exercise demo video resolution for the LIFT knowledge base.
 *
 * Bundled demo clips are short, silent movement loops shown at the top of an
 * exercise guide. They live in `assets/exercises/demos/<kb-id>.mp4` (demo 1)
 * and `<kb-id>__2.mp4` (a second version), ship inside the app, and work
 * offline. The separately published clips (display-name files from the video
 * agent) are discovered from GitHub at runtime by `videoCatalog.ts`; the
 * bundled clips are the offline fallback.
 *
 * Metro cannot `require()` a dynamic path, so this module keeps a static
 * registry of the clips actually bundled. An exercise with no clip gets the
 * placeholder tile (the primary-muscle icon + "coming soon") — no guide ever
 * renders an empty media frame. An exercise can have several versions; the
 * guide lets the user switch between them.
 *
 * The REGISTRY block is generated by `scripts/gen-exercise-demo-registry.mjs`.
 * Re-run that script after adding a clip. The file name must start with the
 * exercise's permanent KB id (the same id the seeded exercise row uses).
 *
 * Clip contract (enforced by `scripts/test-exercise-demo.mjs`):
 *   720 × 720, 24 fps, 3 s loop, H.264 High, yuv420p, no audio, ≤ 500 KB.
 */

/** Every bundled clip must match this contract. */
export const DEMO_SPEC = {
  size: 720,
  fps: 24,
  seconds: 3,
  maxBytes: 500_000,
} as const;

// === BEGIN GENERATED REGISTRY ===
const REGISTRY: Record<string, number[]> = {
  'barbell-deadlift': [
    require('../../assets/exercises/demos/barbell-deadlift.mp4'),
  ],
  'barbell-squat': [
    require('../../assets/exercises/demos/barbell-squat.mp4'),
  ],
  'bench-press-powerlifting': [
    require('../../assets/exercises/demos/bench-press-powerlifting.mp4'),
  ],
  'dumbbell-bench-press': [
    require('../../assets/exercises/demos/dumbbell-bench-press.mp4'),
    require('../../assets/exercises/demos/dumbbell-bench-press__2.mp4'),
  ],
  'overhead-press': [
    require('../../assets/exercises/demos/overhead-press.mp4'),
  ],
};
const BUNDLED_FILES: readonly string[] = [
  'barbell-deadlift.mp4',
  'barbell-squat.mp4',
  'bench-press-powerlifting.mp4',
  'dumbbell-bench-press.mp4',
  'dumbbell-bench-press__2.mp4',
  'overhead-press.mp4',
];
// === END GENERATED REGISTRY ===

/**
 * Every bundled clip for an exercise, oldest version first. Empty when the
 * exercise has none yet. Pass the exercise's `kbId` (seeded rows use the KB id
 * as their row id too).
 */
export function resolveExerciseDemos(exerciseId?: string | null): readonly number[] {
  if (!exerciseId) return [];
  return REGISTRY[exerciseId] ?? [];
}

/** The first bundled clip for an exercise, or null when it has none yet. */
export function resolveExerciseDemo(exerciseId?: string | null): number | null {
  return resolveExerciseDemos(exerciseId)[0] ?? null;
}

/** How many demo versions are bundled for an exercise. */
export function exerciseDemoCount(exerciseId?: string | null): number {
  return resolveExerciseDemos(exerciseId).length;
}

/** True when at least one real clip is bundled for this exercise. */
export function hasExerciseDemo(exerciseId?: string | null): boolean {
  return exerciseDemoCount(exerciseId) > 0;
}

/** The KB ids that currently have a bundled clip — used by the registry test. */
export function bundledDemoIds(): string[] {
  return Object.keys(REGISTRY).sort();
}

/** The exact bundled file names, so the runtime catalogue can exclude them. */
export function bundledDemoFileNames(): readonly string[] {
  return BUNDLED_FILES;
}
