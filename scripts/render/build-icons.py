#!/usr/bin/env python3
"""Turn the Blender renders into the PNGs the app ships.

The renderer writes three 640 px images per icon: the plain body, the body with
the dark-theme muscle painted, and the body with the light-theme muscle painted.
This script

  1. recovers the painted area from the colour difference (the muscle pass is
     opaque, so the mask is what the render actually shows),
  2. tints the bare skin of the light-theme image so the figure sits on the
     light tile at the same contrast the dark one has on the dark tile,
  3. trims to the figure, squares the crop, and downsamples to 288 px,
  4. writes assets/icons-3d/{dark,light}/<slug>.png and qa.json.

Run from lift-app/:  python3 scripts/render/build-icons.py [--src DIR] [--check]
Requires Pillow (system python). The Blender side is render-muscle.py.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(APP, "assets", "icons-3d")

# Must match render-muscle.py's REGIONS keys. Slug -> canonical muscle id.
ICONS = {
    "chest": "Chest",
    "abs": "Abs",
    "quadriceps": "Quadriceps",
    "middle-delts": "Middle Delts",
    "front-delts": "Front Delts",
    "rear-delts": "Rear Delts",
    "biceps": "Biceps",
    "triceps": "Triceps",
    "forearms": "Forearms",
    "lats": "Lats",
    "upper-back": "Upper Back",
    "lower-back": "Lower Back",
    "glutes": "Glutes",
    "hamstrings": "Hamstrings",
    "calves": "Calves",
    "abductors": "Abductors",
    "adductors": "Adductors",
    "neck": "Neck",
}
SLUGS = list(ICONS)
TS_MAP = os.path.join(APP, "src", "components", "icons", "muscleRenders.generated.ts")

SIZE = 288           # delivered edge; the tiles that use these are 40-44 pt
MARGIN = 0.035       # padding around the trimmed figure, fraction of the side
LIGHT_SKIN = 0.235   # linear multiplier for the bare skin on the light tile

# qa.py's verdicts, written next to the renders and copied into qa.json.
QA_NAMES = ["body_coverage", "mask_ratio", "mask_outside", "soft_edge",
            "contrast48", "mask_clip"]


def srgb_to_linear(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear_to_srgb(c: float) -> float:
    c = max(0.0, min(1.0, c))
    return c * 12.92 if c <= 0.0031308 else 1.055 * (c ** (1 / 2.4)) - 0.055


def tint_skin(img: Image.Image, painted: Image.Image, factor: float) -> Image.Image:
    """Darken the unpainted skin in linear light, leave the muscle as rendered."""
    src = img.load()
    ref = painted.load()
    out = Image.new("RGBA", img.size)
    dst = out.load()
    lut = [srgb_to_linear(i / 255.0) for i in range(256)]
    back = [int(round(linear_to_srgb(i / 1024.0) * 255)) for i in range(1025)]
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = src[x, y]
            if a == 0:
                dst[x, y] = (0, 0, 0, 0)
                continue
            pr, pg, pb, _ = ref[x, y]
            d = max(abs(pr - r), abs(pg - g), abs(pb - b))
            # 1 where the muscle is painted, 0 on bare skin, feathered between.
            m = min(1.0, d / 64.0)
            k = factor + (1.0 - factor) * m
            dst[x, y] = (
                back[int(lut[r] * k * 1024)],
                back[int(lut[g] * k * 1024)],
                back[int(lut[b] * k * 1024)],
                a,
            )
    return out


def trim_square(img: Image.Image) -> Image.Image:
    box = img.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    if not box:
        return img
    left, top, right, bottom = box
    side = max(right - left, bottom - top)
    pad = int(round(side * MARGIN))
    side += 2 * pad
    cx, cy = (left + right) / 2, (top + bottom) / 2
    left = int(round(cx - side / 2))
    top = int(round(cy - side / 2))
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(img, (-left, -top))
    return canvas


def sha256(path: str) -> str:
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def ts_source() -> str:
    lines = [
        "/**",
        " * AUTO-GENERATED by scripts/render/build-icons.py — do not edit by hand.",
        " *",
        " * Theme-specific renders of the 3D muscle mannequin. Both variants are",
        " * baked at build time (the muscle is a lit pass, not a tint), so the app",
        " * only picks a file. Ids missing here fall back to the vector artwork in",
        " * iconArt.generated.ts / muscleIcons.tsx.",
        " */",
        "import type { ImageSourcePropType } from 'react-native';",
        "",
        "export interface MuscleRender {",
        "  dark: ImageSourcePropType;",
        "  light: ImageSourcePropType;",
        "}",
        "",
        "export const MUSCLE_RENDERS: Record<string, MuscleRender> = {",
    ]
    for slug, ident in ICONS.items():
        key = ident if ident.isidentifier() else f"'{ident}'"
        lines.append(
            f"  {key}: {{ dark: require('../../../assets/icons-3d/dark/{slug}.png'), "
            f"light: require('../../../assets/icons-3d/light/{slug}.png') }},"
        )
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="/tmp/lift-icons",
                    help="directory holding <slug>-body.png and <slug>-muscle-*.png "
                         "(the driver's OUT)")
    ap.add_argument("--qa", default=None,
                    help="qa.py transcript to fold into qa.json (default: <src>/qa.txt)")
    ap.add_argument("--check", action="store_true",
                    help="verify the shipped assets against qa.json instead of writing")
    args = ap.parse_args()

    if args.check:
        return check()

    qa_txt = args.qa or os.path.join(args.src, "qa.txt")
    verdicts = parse_qa(qa_txt)

    report = {"size": SIZE, "iconCount": len(SLUGS), "icons": {}, "verdicts": verdicts}
    for slug in SLUGS:
        body_p = os.path.join(args.src, f"{slug}-body.png")
        dark_p = os.path.join(args.src, f"{slug}-muscle-dark.png")
        light_p = os.path.join(args.src, f"{slug}-muscle-light.png")
        for p in (body_p, dark_p, light_p):
            if not os.path.exists(p):
                print(f"missing render: {p}", file=sys.stderr)
                return 1
        body = Image.open(body_p).convert("RGBA")
        dark = Image.open(dark_p).convert("RGBA")
        light = Image.open(light_p).convert("RGBA")

        dark_out = trim_square(dark).resize((SIZE, SIZE), Image.LANCZOS)
        light_out = trim_square(tint_skin(light, body, LIGHT_SKIN)).resize(
            (SIZE, SIZE), Image.LANCZOS)

        for mode, image in (("dark", dark_out), ("light", light_out)):
            d = os.path.join(OUT, mode)
            os.makedirs(d, exist_ok=True)
            path = os.path.join(d, f"{slug}.png")
            image.save(path, optimize=True)

        report["icons"][slug] = {
            "dark": sha256(os.path.join(OUT, "dark", f"{slug}.png")),
            "light": sha256(os.path.join(OUT, "light", f"{slug}.png")),
            "qa": verdicts.get(slug, "MISSING"),
        }
        print(f"{slug:14s} {report['icons'][slug]['qa']}")

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "qa.json"), "w") as fh:
        json.dump(report, fh, indent=2, sort_keys=True)
        fh.write("\n")
    with open(TS_MAP, "w") as fh:
        fh.write(ts_source())

    failed = [s for s, v in report["icons"].items() if v["qa"] != "PASS"]
    total = sum(os.path.getsize(os.path.join(OUT, m, f"{s}.png"))
                for s in SLUGS for m in ("dark", "light"))
    print(f"\n{len(SLUGS) - len(failed)}/{len(SLUGS)} PASS, {total / 1024:.0f} KiB total")
    return 1 if failed else 0


def parse_qa(path: str) -> dict:
    """Read qa.py's text transcript: a PASS/FAIL line per icon, then metrics."""
    out = {}
    if not os.path.exists(path):
        return out
    current = None
    with open(path) as fh:
        for line in fh:
            line = line.rstrip()
            if line.startswith(("PASS ", "FAIL ")):
                verdict, name = line.split(None, 1)
                current = name.strip()
                out[current] = verdict
            elif current and line.strip().startswith("!"):
                pass
    return out


def check() -> int:
    """Fail if a shipped asset is missing, wrong-sized, or not the verified one."""
    qa_path = os.path.join(OUT, "qa.json")
    if not os.path.exists(qa_path):
        print("assets/icons-3d/qa.json is missing — run scripts/render/build-icons.py")
        return 1
    with open(qa_path) as fh:
        report = json.load(fh)
    bad = 0
    for slug in SLUGS:
        entry = report.get("icons", {}).get(slug)
        if not entry:
            print(f"FAIL {slug}: not in qa.json")
            bad += 1
            continue
        if entry.get("qa") != "PASS":
            print(f"FAIL {slug}: QA verdict {entry.get('qa')}")
            bad += 1
        for mode in ("dark", "light"):
            path = os.path.join(OUT, mode, f"{slug}.png")
            if not os.path.exists(path):
                print(f"FAIL {slug}: missing {mode} asset")
                bad += 1
                continue
            with Image.open(path) as im:
                if im.size != (SIZE, SIZE):
                    print(f"FAIL {slug}: {mode} is {im.size}, expected {(SIZE, SIZE)}")
                    bad += 1
            if sha256(path) != entry[mode]:
                print(f"FAIL {slug}: {mode} does not match the verified build")
                bad += 1
    with open(TS_MAP) as fh:
        if fh.read() != ts_source():
            print("FAIL: muscleRenders.generated.ts is stale — rerun build-icons.py")
            bad += 1
    if bad:
        print(f"{bad} problem(s)")
        return 1
    print(f"OK: {len(SLUGS)} icons, 2 themes, all verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
